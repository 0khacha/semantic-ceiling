import json
import matplotlib.pyplot as plt
import os

def main():
    with open("results/hyperparameter_sweep_full.json", "r") as f:
        data = json.load(f)

    # Find global max
    best_overall = max(data, key=lambda x: x["F1"])
    print(f"EMPIRICAL MAXIMUM: C={best_overall['C']}, Threshold={best_overall['threshold']}, F1={best_overall['F1']:.4%}")
    
    # Thesis check
    thesis_C = 15.0
    thesis_threshold = 0.35
    
    matches_thesis = (best_overall['C'] == thesis_C and best_overall['threshold'] == thesis_threshold)
    print(f"Matches Thesis (C={thesis_C}, threshold={thesis_threshold})? {'YES' if matches_thesis else 'NO'}")

    # Extract max F1 for each C for plotting
    c_f1_map = {}
    for entry in data:
        c = entry["C"]
        f1 = entry["F1"]
        if c not in c_f1_map or f1 > c_f1_map[c]:
            c_f1_map[c] = f1

    c_vals = sorted(list(c_f1_map.keys()))
    f1_vals = [c_f1_map[c] for c in c_vals]

    plt.figure(figsize=(10, 6))
    
    # Plot data points
    plt.plot(c_vals, f1_vals, marker='o', linestyle='-', color='#1f77b4', label='Best F1 per C')
    
    # Highlight max point
    plt.scatter([best_overall['C']], [best_overall['F1']], color='red', s=150, zorder=5, label=f"Max F1 (C={best_overall['C']}, thr={best_overall['threshold']})")
    
    # Aesthetics
    plt.title("Validation F1 Score vs Regularization Parameter (C)", fontsize=14, pad=15)
    plt.xlabel("C Value (Inverse Regularization Strength)", fontsize=12)
    plt.ylabel("Best Validation F1 Score", fontsize=12)
    
    # Format X-axis for better visibility if needed (e.g. log scale if range is large)
    if max(c_vals) / min(c_vals) > 100:
        plt.xscale('log')
        plt.xlabel("C Value (log scale)")
        
        # Format the x ticks to show actual values
        plt.xticks(c_vals, labels=[str(c) for c in c_vals])

    # Add a caption
    plt.figtext(0.5, 0.01, "Data Source: results/hyperparameter_sweep_full.json generated by scripts/train/exhaustive_search_logging.py", wrap=True, horizontalalignment='center', fontsize=9, style='italic')
    
    plt.grid(True, linestyle='--', alpha=0.7)
    plt.legend(loc='lower right')
    
    # Save figure
    os.makedirs("docs/figures", exist_ok=True)
    out_path = "docs/figures/hyperparameter_c_selection.png"
    plt.tight_layout(rect=[0, 0.03, 1, 1])
    plt.savefig(out_path, dpi=300)
    print(f"Plot saved to {out_path}")

if __name__ == "__main__":
    main()
